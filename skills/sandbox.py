_bwrap_lock = threading.Lock()
_bwrap_state: bool | None = None


def _bwrap_available() -> bool:
    """Whether bubblewrap can create the namespaces we need, cached.

    ``bwrap`` being on PATH is not enough: some distributions ship it while an
    AppArmor profile denies unprivileged user namespaces, in which case every
    invocation fails. So this actually runs it once.
    """
    global _bwrap_state
    if _bwrap_state is not None:
        return _bwrap_state
    with _bwrap_lock:
        if _bwrap_state is not None:
            return _bwrap_state
        _bwrap_state = _probe_bwrap()
        return _bwrap_state


def _probe_bwrap() -> bool:
    binary = shutil.which("bwrap")
    if binary is None:
        logger.debug("bubblewrap is not installed — sandbox will run at rlimits level only")
        return False

    truthy = shutil.which("true") or "/bin/true"
    probe = [
        binary,
        "--ro-bind", "/", "/",
        "--dev", "/dev",
        "--proc", "/proc",
        "--unshare-pid",
        "--unshare-net",
        "--die-with-parent",
        "--clearenv",
        truthy,
    ]
    try:
        completed = subprocess.run(
            probe, capture_output=True, text=True, timeout=_BWRAP_TIMEOUT
        )
    except (OSError, subprocess.SubprocessError) as exc:
        logger.info("bubblewrap is present but unusable (%s)", exc)
        return False

    if completed.returncode != 0:
        logger.info(
            "bubblewrap is present but unusable here (%s)",
            (completed.stderr or "").strip()[:200] or f"exit {completed.returncode}",
        )
        return False
    return True


def reset_bwrap_probe() -> None:
    """Forget the cached bubblewrap result. Used by the self-test."""
    global _bwrap_state
    with _bwrap_lock:
        _bwrap_state = None



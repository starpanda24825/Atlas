def _split_test_input(test_input: Any) -> tuple[list[Any], dict[str, Any]]:
    """Turn ``test_input`` into positional and keyword arguments.

    A mapping becomes keyword arguments — ``run(**test_input)`` — because that
    is how the skill schema documents its parameters. A list or tuple becomes
    positional arguments, and anything else is a single positional argument.
    """
    if test_input is None:
        return [], {}
    if isinstance(test_input, Mapping):
        return [], {str(key): value for key, value in test_input.items()}
    if isinstance(test_input, (list, tuple)):
        return list(test_input), {}
    return [test_input], {}


def _jsonable(value: Any, depth: int = 8) -> Any:
    """Parent-side twin of the harness's helper, for the job file."""
    if depth <= 0:
        return repr(value)
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple)):
        return [_jsonable(item, depth - 1) for item in value]
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item, depth - 1) for key, item in value.items()}
    if isinstance(value, (set, frozenset)):
        return [_jsonable(item, depth - 1) for item in sorted(value, key=repr)]
    if isinstance(value, (bytes, bytearray)):
        return f"<{len(value)} bytes>"
    try:
        path = os.fspath(value)
    except (TypeError, ValueError):
        return repr(value)
    return path.decode("utf-8", "replace") if isinstance(path, bytes) else path


def _kill_group(process: subprocess.Popen) -> None:
    """Kill the child and everything it started.

    The child leads its own session, so one ``killpg`` reaches the interpreter,
    anything it forked, and — for a bwrap child — the bubblewrap supervisor,
    which takes the namespace with it via ``--die-with-parent``.
    """
    for signal_number in (signal.SIGKILL,):
        try:
            os.killpg(os.getpgid(process.pid), signal_number)
            break
        except (ProcessLookupError, PermissionError, OSError):
            continue
    else:  # pragma: no cover - the group was already gone
        pass
    try:
        process.kill()
    except (ProcessLookupError, OSError):
        pass
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:  # pragma: no cover
        logger.warning("sandboxed process %s survived SIGKILL", process.pid)


def _read_capped(path: Path, limit: int) -> tuple[str, bool]:
    """Read a captured stream, truncating to ``limit`` characters."""
    try:
        raw = path.read_bytes()
    except OSError:
        return "", False
    text = raw.decode("utf-8", "replace")
    if len(text) <= limit:
        return text, False
    return text[:limit] + f"\n… [{len(text) - limit} more characters in {path.name}]", True


def _signal_reason(code: int) -> str:
    """Human name for a negative return code."""
    if code >= 0:
        return ""
    number = -code
    name = signal.Signals(number).name if number in {s.value for s in signal.Signals} else f"signal {number}"
    return name


def _mb(count: int) -> str:
    """Bytes as a whole number of megabytes, for messages a person reads."""
    return f"{count // (1024 * 1024)}"


def _append_captured(detail: str, result: SandboxResult, limit: int = 2000) -> str:
    """Add the run's own stdout to a failure explanation.

    "test() returned False" is not something a model — or a person — can act on,
    and a skill that catches its own exceptions usually reports the real reason
    by printing or by returning it, not by letting it escape. Whatever the skill
    printed is therefore appended to the explanation. stderr is deliberately not
    repeated here: it is already part of ``result.error``.
    """
    printed = (result.output or "").strip()
    if not printed:
        return detail
    if len(printed) > limit:
        printed = printed[:limit] + "\n… [truncated]"
    return f"{detail}\n\n--- what the skill printed ---\n{printed}"


def _blas_hint(stderr: str, memory_bytes: int) -> str:
    """Explain the OpenBLAS abort, which otherwise reads as a mystery.

    Importing numpy under a 512 MB address-space cap fails with "OpenBLAS error:
    Memory allocation still failed after 10 retries" and kills the process.
    Measured on this machine, numpy needs about 1024 MB of *address space* —
    not memory the skill actually uses, because OpenBLAS reserves large
    thread buffers up front. Without this hint the user sees an unexplained
    abort in a skill that did nothing wrong.
    """
    if "OpenBLAS" not in stderr and "Memory allocation still failed" not in stderr:
        return ""
    return (
        f"\n\nThe BLAS allocator refused to start under the {_mb(memory_bytes)} MB address-space "
        "cap. That is not the skill using too much memory: OpenBLAS reserves large "
        "thread buffers before it does any work, so importing numpy (or anything built "
        "on it) needs roughly 1024 MB of address space. Raise it for this skill with a "
        "'MEMORY: 1024' line in its docstring, or set ATLAS_SANDBOX_MEMORY_MB."
    )



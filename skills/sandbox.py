        reset_bwrap_probe()
        available = _bwrap_available()
        sandbox = SkillSandbox(sandbox_dir=workspace, timeout=20)
        check("sandbox constructed", sandbox is not None)
        check("isolation level reported", sandbox.isolation in ("bwrap", "rlimits"),
              sandbox.isolation)
        check("level matches the probe",
              (sandbox.isolation == "bwrap") is available,
              f"probe={available}")
        check("describe() says what is enforced", "timeout" in sandbox.describe(),
              sandbox.describe())
        print(f"\n  this machine: {sandbox.describe()}")

        # --- a skill that works ------------------------------------------
        print("\n--- a working skill ---")
        good = sandbox.execute_in_sandbox(_GOOD_SKILL, {"numbers": [1, 2, 3]})
        check("success is True", good.success, good.error[:200])
        check("the return value comes back", good.return_value == {"total": 6, "count": 3},
              repr(good.return_value))
        check("stdout was captured", "adding 3 numbers" in good.output, repr(good.output))
        check("stderr was captured", "to stderr" in good.error, repr(good.error))
        check("execution_time is plausible", 0 < good.execution_time < 20,
              f"{good.execution_time:.2f}s")
        check("no timeout", good.timed_out is False)
        check("exit code is 0", good.exit_code == 0, str(good.exit_code))
        check("result is truthy", bool(good) is True)
        check("as_dict is complete", set(good.as_dict()) >=
              {"success", "output", "error", "execution_time", "return_value"})

        # positional args, keyword args, and no args
        positional = sandbox.execute_in_sandbox(_ARGS_SKILL, ["left", "right"])
        check("a list becomes positional arguments",
              positional.success and positional.return_value == {"args": ["left", "right"]},
              positional.success and repr(positional.return_value) or positional.error[:120])

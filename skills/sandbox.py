_sandbox: SkillSandbox | None = None
_sandbox_lock = threading.Lock()


def get_sandbox(**kwargs: Any) -> SkillSandbox:
    """Process-wide sandbox, built once.

    Building it repeatedly is harmless but re-runs the bubblewrap capability
    probe the first time, so the daemon, the builder and the registry should
    share this one.
    """
    global _sandbox
    if _sandbox is None:
        with _sandbox_lock:
            if _sandbox is None:
                _sandbox = SkillSandbox(**kwargs)
    return _sandbox


def reset_sandbox() -> None:
    """Drop the shared instance so the next call rebuilds it."""
    global _sandbox
    with _sandbox_lock:
        _sandbox = None



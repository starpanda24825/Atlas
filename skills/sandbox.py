_HARNESS_SOURCE = r'''"""Generated by skills/sandbox.py. Runs one skill call.

Invoked as: python _atlas_harness.py <job.json> <result.json>

The outcome goes to <result.json>; stdout and stderr are left untouched so the
parent captures the skill's own output verbatim. The exit code stays 0 even
when the skill fails, because a non-zero exit is reserved for "the sandbox
itself could not run this".
"""
import json
import os
import resource
import sys
import traceback
from importlib.util import module_from_spec, spec_from_file_location

_MAX_DEPTH = 8


def jsonable(value, depth=0):
    """Best-effort JSON-safe rendering of whatever the skill returned."""
    if depth > _MAX_DEPTH:
        return repr(value)
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple)):
        return [jsonable(item, depth + 1) for item in value]
    if isinstance(value, dict):
        return {str(key): jsonable(item, depth + 1) for key, item in value.items()}
    if isinstance(value, (set, frozenset)):
        return [jsonable(item, depth + 1) for item in sorted(value, key=repr)]
    if isinstance(value, (bytes, bytearray)):
        return "<%d bytes>" % len(value)
    try:
        path = os.fspath(value)
    except (TypeError, ValueError):
        return repr(value)
    return path.decode("utf-8", "replace") if isinstance(path, bytes) else path


def apply_limits(job):
    """Set the kernel limits before the skill's module is imported.

    Order matters: importing the skill is where a runaway usually starts, so
    the cap has to already be in place.
    """
    memory = int(job["memory_bytes"])
    for name, value in (
        ("RLIMIT_AS", memory),
        ("RLIMIT_FSIZE", int(job.get("file_bytes") or memory)),
        ("RLIMIT_CORE", 0),
    ):
        which = getattr(resource, name, None)
        if which is None:
            continue
        try:
            resource.setrlimit(which, (value, value))
        except (ValueError, OSError):
            pass


def load(spec):
    path = spec["skill_path"]
    name = spec.get("module_name") or "atlas_skill"
    module_spec = spec_from_file_location(name, path)
    if module_spec is None or module_spec.loader is None:
        raise ImportError("could not load a module from %s" % path)
    module = module_from_spec(module_spec)
    sys.modules[name] = module
    module_spec.loader.exec_module(module)
    return module


def write_result(path, envelope):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(envelope, handle)


def main(argv):
    job_path, result_path = argv[1], argv[2]
    with open(job_path, "r", encoding="utf-8") as handle:
        job = json.load(handle)

    apply_limits(job)

    envelope = {"ok": False, "return_value": None, "traceback": "", "stage": ""}
    try:
        module = load(job)
    except BaseException:
        envelope["stage"] = "import"
        envelope["traceback"] = traceback.format_exc()
        write_result(result_path, envelope)
        return 0

    target = getattr(module, job["function"], None)
    if not callable(target):
        envelope["stage"] = "lookup"
        envelope["traceback"] = "%s() is not defined, or is not callable" % job["function"]
        write_result(result_path, envelope)
        return 0

    try:
        value = target(*job.get("args", []), **job.get("kwargs", {}))
    except BaseException:
        envelope["stage"] = "call"
        envelope["traceback"] = traceback.format_exc()
    else:
        envelope["ok"] = True
        envelope["return_value"] = jsonable(value)

    write_result(result_path, envelope)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
'''



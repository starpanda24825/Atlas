def _dotted(node: ast.AST | None, aliases: Mapping[str, str]) -> str | None:
    """Resolve ``o.system`` to ``os.system``, following ``import ... as ...``.

    Without the alias table every one of these checks is trivially bypassed by
    ``import os as o``, which is exactly the kind of rewriting a model produces
    without meaning anything by it.
    """
    if isinstance(node, ast.Name):
        return aliases.get(node.id, node.id)
    if isinstance(node, ast.Attribute):
        base = _dotted(node.value, aliases)
        return f"{base}.{node.attr}" if base else None
    return None


def _import_aliases(tree: ast.AST) -> dict[str, str]:
    """Map each locally bound name to the dotted path it came from."""
    aliases: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    aliases[alias.asname] = alias.name
                else:
                    top = alias.name.split(".")[0]
                    aliases[top] = top
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
            for alias in node.names:
                if alias.name == "*":
                    continue
                aliases[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return aliases


def _literal_string(node: ast.AST | None) -> str | None:
    """The string value of a literal node, or None if it is computed.

    Adjacent literals are folded, so ``"api." "example.com"`` counts as
    literal; anything with a variable in it does not.
    """
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left = _literal_string(node.left)
        right = _literal_string(node.right)
        if left is not None and right is not None:
            return left + right
    if isinstance(node, ast.JoinedStr):
        parts: list[str] = []
        for value in node.values:
            if isinstance(value, ast.Constant) and isinstance(value.value, str):
                parts.append(value.value)
            else:
                return None
        return "".join(parts)
    return None


def _module_constants(tree: ast.AST) -> dict[str, Any]:
    """Top-level assignments whose value is a literal.

    Skills declare things like ``REQUIRES_NETWORK = True`` or ``MEMORY_MB =
    1024``; this is how those are read without importing anything.
    """
    values: dict[str, Any] = {}
    for node in getattr(tree, "body", ()):
        targets: list[ast.expr] = []
        if isinstance(node, ast.Assign):
            targets = list(node.targets)
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets = [node.target]
        else:
            continue
        for target in targets:
            if not isinstance(target, ast.Name):
                continue
            try:
                values[target.id] = ast.literal_eval(node.value)
            except (ValueError, TypeError, SyntaxError):
                continue
    return values


def _matches_module(name: str, prefixes: Sequence[str]) -> str | None:
    """Return the matching prefix for a dotted module name, or None."""
    for prefix in prefixes:
        if name == prefix or name.startswith(prefix + "."):
            return prefix
    return None


def _host_of(url: str) -> str | None:
    """Host from a URL, tolerating bare ``host/path`` strings."""
    text = url.strip()
    if not text:
        return None
    if "://" not in text:
        text = "//" + text
    try:
        host = urlparse(text).hostname
    except ValueError:
        return None
    if not host:
        return None
    return host.lower().strip(".")


def _host_allowed(host: str, allowed: Iterable[str]) -> bool:
    """Whether ``host`` matches the whitelist or the skill's own declaration.

    A declaration of ``example.com`` covers ``api.example.com``, because that is
    what a skill author means by naming a site; ``*`` covers everything and is
    reported as such.
    """
    host = host.lower().strip(".")
    for entry in allowed:
        candidate = str(entry).lower().strip().strip(".").strip()
        if not candidate:
            continue
        if candidate == "*":
            return True
        if host == candidate or host.endswith("." + candidate):
            return True
    return False


def declared_permissions(code_string: str) -> dict[str, Any]:
    """What a skill says it needs, read statically from its docstring.

    Recognised, in either the module docstring or as a module-level constant:

    ``NETWORK:``
        ``none`` (the default), ``*`` for anything, or a comma/space separated
        list of hosts. A host covers its subdomains.
    ``SUBPROCESS:``
        ``allowed`` or ``denied``.
    ``MEMORY:``
        ``512``, ``1024``, ``2 GB`` — raises this skill's address-space cap,
        clamped to ``SKILL_SANDBOX_MAX_MEMORY_MB``.

    Equivalently ``REQUIRES_NETWORK = True``, ``NETWORK_HOSTS = ("a.com",)``,
    ``REQUIRES_SUBPROCESS = True`` and ``MEMORY_MB = 1024``.

    Returns a dict with ``network``, ``hosts``, ``subprocess``, ``memory_mb``
    and ``parsed`` (False when the source does not even parse).
    """
    source = str(code_string or "")
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return {
            "network": False,
            "hosts": frozenset(),
            "subprocess": False,
            "memory_mb": None,
            "parsed": False,
        }

    docstring = ast.get_docstring(tree) or ""
    constants = _module_constants(tree)

    network = False
    hosts: set[str] = set()

    field = _NETWORK_FIELD.search(docstring)
    if field:
        raw = field.group(1).strip().strip("\"'")
        if raw.lower() in _NO_VALUES:
            network = False
        elif raw in ("*", "any", "all") or raw.lower() in _YES_VALUES:
            network = True
            hosts.add("*")
        else:
            network = True
            hosts.update(
                part.strip().lower() for part in re.split(r"[,\s]+", raw) if part.strip()
            )

    if constants.get("REQUIRES_NETWORK") is True:
        network = True

    declared_hosts = constants.get("NETWORK_HOSTS")
    if isinstance(declared_hosts, (list, tuple, set, frozenset)):
        network = True
        hosts.update(str(item).strip().lower() for item in declared_hosts if str(item).strip())

    subprocess_allowed = constants.get("REQUIRES_SUBPROCESS") is True
    field = _SUBPROCESS_FIELD.search(docstring)
    if field:
        raw = field.group(1).strip().strip("\"'").lower()
        if raw in _NO_VALUES:
            subprocess_allowed = False
        elif raw in _YES_VALUES:
            subprocess_allowed = True

    memory_mb: int | None = None
    constant_memory = constants.get("MEMORY_MB")
    if isinstance(constant_memory, (int, float)) and not isinstance(constant_memory, bool):
        if constant_memory > 0:
            memory_mb = int(constant_memory)
    if memory_mb is None:
        field = _MEMORY_FIELD.search(docstring)
        if field:
            value = int(field.group(1))
            unit = (field.group(2) or "MB").upper()
            memory_mb = value * 1024 if unit == "GB" else value
            if memory_mb <= 0:
                memory_mb = None

    return {
        "network": network,
        "hosts": frozenset(hosts),
        "subprocess": bool(subprocess_allowed),
        "memory_mb": memory_mb,
        "parsed": True,
    }


def validate_skill(
    code_string: str,
    *,
    network_whitelist: Sequence[str] | None = None,
) -> list[str]:
    """Warnings worth showing before this code is allowed to run.

    Not a hard block, and not a substitute for the runtime sandbox — the point
    is to give the person clicking "approve" something concrete to look at.
    Each warning names a line number and says what it noticed and what would
    satisfy it.

    Deliberately quiet about things that are ordinary in a skill: file reads,
    ``random``, ``os.path``, ``json``, printing, and imports of anything that
    is not on the network or process lists below.
    """
    source = str(code_string or "")
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        return [f"line {exc.lineno}: syntax error — {exc.msg}. Nothing else could be checked."]

    permissions = declared_permissions(source)
    allowed_hosts = set(permissions["hosts"])
    whitelist = tuple(
        SKILL_NETWORK_WHITELIST if network_whitelist is None else network_whitelist
    )
    allowed_hosts.update(str(item) for item in whitelist)

    aliases = _import_aliases(tree)
    warnings: list[str] = []

    # --- imports -------------------------------------------------------
    for node in ast.walk(tree):
        modules: list[str] = []
        if isinstance(node, ast.Import):
            modules = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
            modules = [node.module]

        for module in modules:
            if _matches_module(module, _NETWORK_MODULES):
                if not permissions["network"]:
                    warnings.append(
                        f"line {node.lineno}: imports {module!r} for network access, "
                        "but the docstring declares no NETWORK: permission — add "
                        "'NETWORK: <hosts>' or remove the network use"
                    )
                continue
            prefix = _matches_module(module, tuple(_DANGEROUS_MODULES))
            if prefix is None:
                continue
            reason = _DANGEROUS_MODULES[prefix]
            if prefix == "subprocess" and permissions["subprocess"]:
                continue
            if prefix == "subprocess":
                warnings.append(
                    f"line {node.lineno}: imports 'subprocess' — {reason}. It needs "
                    "'SUBPROCESS: allowed' in the docstring, or the user's approval"
                )
            else:
                warnings.append(f"line {node.lineno}: imports {module!r}, which {reason}")

    # --- calls ---------------------------------------------------------
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            warnings.extend(_call_warnings(node, aliases, permissions, allowed_hosts))

    # --- URLs in plain strings ----------------------------------------
    warnings.extend(_url_literal_warnings(tree, allowed_hosts))

    # --- environment ---------------------------------------------------
    warnings.extend(_environment_warnings(tree, aliases))

    # De-duplicate while keeping order: the same call seen twice reads as noise.
    seen: set[str] = set()
    unique: list[str] = []
    for warning in warnings:
        if warning in seen:
            continue
        seen.add(warning)
        unique.append(warning)
    return unique


#: Environment variables the sandbox itself sets. Reading one of these is
#: correct usage, so it must not be reported as a problem — ``ATLAS_SANDBOX_DIR``
#: in particular is the documented way for a skill to find its writable
#: directory, and warning about it would tell the author their working code is
#: broken.
_PROVIDED_ENV = frozenset(
    {
        _SANDBOX_ENV_MARKER,
        _SANDBOX_DIR_VAR,
        "HOME",
        "TMPDIR",
        "PATH",
        "LANG",
        "LC_ALL",
        "PYTHONHASHSEED",
        "PYTHONDONTWRITEBYTECODE",
        "PYTHONIOENCODING",
    }
)


def _environment_warnings(tree: ast.AST, aliases: Mapping[str, str]) -> list[str]:
    """Warn when a skill reaches for environment variables it will not find.

    Only unset ones are reported. The sandbox clears the environment and then
    sets a handful of its own, so ``os.environ["ATLAS_SANDBOX_DIR"]`` works and
    ``os.getenv("OPENAI_API_KEY")`` silently returns None, and only the second
    is worth telling the user about.
    """
    # Attributes that are the target of a subscript are handled by the
    # subscript branch, so note them to avoid reporting the same access twice.
    subscript_targets = {
        id(node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Subscript) and isinstance(node.value, ast.AST)
    }

    warnings: list[str] = []
    for node in ast.walk(tree):
        key: str | None = None
        honest = True

        if isinstance(node, ast.Subscript):
            if _dotted(node.value, aliases) not in ("os.environ", "os.environb"):
                continue
            key = _literal_string(node.slice)
            # A computed key could be anything, including a variable the
            # sandbox does set, so stay quiet about it.
            honest = key is not None
        elif isinstance(node, ast.Call):
            name = _dotted(node.func, aliases)
            if name not in ("os.getenv", "os.environ.get", "os.environb.get"):
                continue
            key = _literal_string(node.args[0]) if node.args else None
            honest = key is not None
        elif isinstance(node, ast.Attribute):
            if id(node) in subscript_targets:
                continue
            if _dotted(node, aliases) not in ("os.environ", "os.environb"):
                continue
            # The whole mapping, e.g. dict(os.environ) — it will be tiny.
            key = None
        else:
            continue

        if not honest:
            # A computed key could name anything, including a variable the
            # sandbox does set, so there is nothing honest to say about it.
            continue
        if key is not None and key in _PROVIDED_ENV:
            continue

        where = f"the variable {key!r}" if key else "the environment"
        warnings.append(
            f"line {node.lineno}: reads {where} — the sandbox clears the environment "
            "and sets only a few variables, so an API key or any other secret will "
            f"be absent (set: {', '.join(sorted(_PROVIDED_ENV))})"
        )
    return warnings


def _call_warnings(
    node: ast.Call,
    aliases: Mapping[str, str],
    permissions: Mapping[str, Any],
    allowed_hosts: set[str],
) -> list[str]:
    """Warnings for a single call site."""
    dotted = _dotted(node.func, aliases)
    if not dotted:
        return []

    warnings: list[str] = []

    if dotted in _EXEC_CALLS:
        name = dotted.split(".")[-1]
        literal = _literal_string(node.args[0]) if node.args else ""
        if literal is None:
            warnings.append(
                f"line {node.lineno}: {name}() runs a string built at runtime, so "
                "nothing it executes can be reviewed — prefer a direct call or a "
                "table of functions"
            )
        else:
            warnings.append(
                f"line {node.lineno}: {name}() executes a hardcoded string; it works, "
                "but a plain call would be clearer and is easier to check"
            )
        return warnings

    if dotted.startswith("subprocess."):
        if not permissions["subprocess"]:
            warnings.append(
                f"line {node.lineno}: {dotted}() runs an external command, which needs "
                "'SUBPROCESS: allowed' in the docstring, or the user's approval"
            )
        return warnings

    if dotted.startswith(_DANGEROUS_PREFIXES):
        warnings.append(f"line {node.lineno}: {dotted}() replaces the current process")
        return warnings

    reason = _DANGEROUS_CALLS.get(dotted)
    if reason is not None:
        warnings.append(f"line {node.lineno}: {dotted}() {reason}")
        return warnings

    if dotted.startswith(("requests.", "httpx.", "aiohttp.")) or _matches_module(
        dotted, _NETWORK_MODULES
    ):
        literals = [text for text in (_literal_string(arg) for arg in node.args) if text]
        hosts = [host for host in (_host_of(text) for text in literals) if host]
        if not hosts:
            if not permissions["network"]:
                warnings.append(
                    f"line {node.lineno}: {dotted}() makes a network request, but no "
                    "NETWORK: permission is declared"
                )
            return warnings
        for host in hosts:
            if _host_allowed(host, allowed_hosts):
                continue
            warnings.append(
                f"line {node.lineno}: contacts {host!r}, which is neither in this "
                "skill's NETWORK: declaration nor in the Atlas network whitelist"
            )
        return warnings

    if dotted in _OPEN_CALLS and node.args:
        path = _literal_string(node.args[0])
        if path and Path(path).is_absolute() and not str(path).startswith(GUEST_SANDBOX):
            warnings.append(
                f"line {node.lineno}: opens the absolute path {path!r}; the sandbox is "
                f"read-only everywhere except {GUEST_SANDBOX}, so this will fail unless "
                "it is a read of a file mounted for that purpose"
            )
    return warnings


def _url_literal_warnings(tree: ast.AST, allowed_hosts: set[str]) -> list[str]:
    """Hosts named in plain string literals, which the call checks can miss."""
    warnings: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        for url in _URL_IN_TEXT.findall(node.value):
            host = _host_of(url)
            if host is None or _host_allowed(host, allowed_hosts):
                continue
            # Covered already if it appears inside a request call; reporting it
            # twice would just make the list longer.
            warnings.append(
                f"line {node.lineno}: mentions the URL {url!r}, whose host {host!r} is "
                "not declared in NETWORK: or the Atlas network whitelist"
            )
    return warnings



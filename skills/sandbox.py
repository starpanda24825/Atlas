"""
Atlas — execution sandbox for untrusted skill code.

Skill files are written by a language model and run on the user's machine, so
they are treated as untrusted: every call happens in a throwaway subprocess
under a hard timeout, an address-space cap, and — where the kernel allows it —
a real sandbox.

What is actually enforced
-------------------------
Two isolation levels, reported on every result as ``SandboxResult.isolation``
so a caller never has to guess:

``bwrap``
    bubblewrap (``bwrap``) puts the child in its own mount, PID, UTS and IPC
    namespaces with **no network namespace**. Measured on this machine, a skill
    running at this level:

    * cannot reach the network — ``socket.create_connection`` raises
      ``OSError [Errno 101] Network is unreachable``
    * cannot read the user's home directory — it is simply not mounted
    * cannot write outside its own run directory — ``/usr`` and ``/etc`` are
      read-only, and everything else is absent
    * sees a cleared environment, so no API key from ``.env`` is visible

``rlimits``
    The fallback when bubblewrap is unavailable (no ``bwrap`` binary, or
    user namespaces denied by the kernel). The timeout and the memory cap still
    apply — those come from the kernel per-process limits, not from
    bubblewrap — but **there is no network or filesystem confinement at all.**
    Untrusted code running at this level can do anything the user can. The
    result carries a warning saying so.

``SKILL_SANDBOX_ISOLATION="bwrap"`` refuses to run at the weaker level instead
of degrading quietly.

What is deliberately *not* claimed
----------------------------------
This is containment for a cooperative-but-untrusted script, not a security
boundary against an adversary who controls the kernel. It shares the user's
uid, so any kernel bug that escapes the namespace escapes the sandbox. For
skills generated by a local model, that trade is the right one; it would not be
for code from the internet.

Where a skill may write
-----------------------
Every call gets its own directory, mounted at ``/tmp/atlas_sandbox`` under
bubblewrap. **That path is not stable across isolation levels** — at the
rlimits level there is no mount, so the writable directory is somewhere else
entirely. A skill must therefore ask rather than assume::

    import os
    from pathlib import Path

    output = Path(os.environ["ATLAS_SANDBOX_DIR"]) / "out.txt"

``ATLAS_SANDBOX=1`` marks a process as sandboxed; ``ATLAS_SANDBOX_DIR`` is the
one directory it can write to. Both are set at either level, so a skill written
against them behaves identically whether or not bubblewrap was available.

To give a skill an input file, pass it to :meth:`SkillSandbox.execute_in_sandbox`
as ``files={"data.csv": "a,b\n1,2\n"}``: the sandbox writes it into the run
directory before the call, and the skill opens
``os.environ["ATLAS_SANDBOX_DIR"] + "/data.csv"``. There is no other way in —
the run directory is created fresh per call and nothing else is mounted.

The static analysis in :func:`validate_skill` is a *review aid*, not a gate: it
produces warnings for the approval dialog, and it can be fooled by code built
at runtime. The runtime limits are what actually hold.

Usage:
    from skills.sandbox import get_sandbox

    result = get_sandbox().execute_in_sandbox(source, {"path": "/tmp/a.csv"})
    if not result:
        print(result.error)
    print(result.return_value, result.artifacts_dir)

Run the built-in check with:
    python3 -m skills.sandbox
"""


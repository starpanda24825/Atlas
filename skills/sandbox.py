@dataclass(frozen=True)
class SandboxResult:
    """Outcome of one sandboxed call.

    ``success`` means the function ran to completion and returned. It says
    nothing about whether the *result* is sensible — only that the skill did
    not raise, time out, or die.
    """

    success: bool
    output: str
    error: str
    execution_time: float

    #: The skill's return value, rendered JSON-safe. Non-JSON values (sets,
    #: Paths, objects) come back as their ``repr``.
    return_value: Any = None

    timed_out: bool = False
    #: ``"bwrap"`` (network and filesystem confined) or ``"rlimits"`` (memory
    #: and time only). Never assume the stronger one.
    isolation: str = "none"
    exit_code: int | None = None
    #: Where the skill's files landed on the host, or None if the run directory
    #: was removed. This is the only place the skill could write.
    artifacts_dir: str | None = None
    artifacts: tuple[str, ...] = ()
    #: True when stdout/stderr were cut short for the result. The whole files
    #: remain in ``artifacts_dir``.
    output_truncated: bool = False
    warnings: tuple[str, ...] = ()

    def __bool__(self) -> bool:
        return self.success

    @property
    def isolated(self) -> bool:
        """True when network and filesystem confinement were actually applied."""
        return self.isolation == "bwrap"

    def as_dict(self) -> dict[str, Any]:
        return {
            "success": self.success,
            "output": self.output,
            "error": self.error,
            "execution_time": self.execution_time,
            "return_value": self.return_value,
            "timed_out": self.timed_out,
            "isolation": self.isolation,
            "exit_code": self.exit_code,
            "artifacts_dir": self.artifacts_dir,
            "artifacts": list(self.artifacts),
            "output_truncated": self.output_truncated,
            "warnings": list(self.warnings),
        }

    def summary(self) -> str:
        """One line for a log or the approval dialog."""
        if self.timed_out:
            return f"timed out after {self.execution_time:.1f}s"
        if self.success:
            return f"ok in {self.execution_time:.2f}s"
        first = self.error.strip().splitlines()[-1] if self.error.strip() else "failed"
        return f"failed in {self.execution_time:.2f}s — {first[:120]}"


@dataclass(frozen=True)
class TestCaseResult:
    """Pass/fail for one thing that was tried."""

    label: str
    passed: bool
    detail: str = ""
    execution_time: float = 0.0

    def as_dict(self) -> dict[str, Any]:
        return {
            "label": self.label,
            "passed": self.passed,
            "detail": self.detail,
            "execution_time": self.execution_time,
        }


@dataclass(frozen=True)
class TestReport:
    """Everything :meth:`SkillSandbox.full_test_cycle` found.

    The first result is always the skill's own ``test()``. The rest correspond
    to the supplied test cases, in order.
    """

    results: tuple[TestCaseResult, ...] = ()
    isolation: str = "none"

    @property
    def total(self) -> int:
        return len(self.results)

    @property
    def passed(self) -> int:
        return sum(1 for item in self.results if item.passed)

    @property
    def failed(self) -> int:
        return self.total - self.passed

    @property
    def ok(self) -> bool:
        return self.total > 0 and self.failed == 0

    @property
    def failures(self) -> tuple[TestCaseResult, ...]:
        return tuple(item for item in self.results if not item.passed)

    def summary(self) -> str:
        if not self.total:
            return "nothing was tested"
        headline = f"{self.passed}/{self.total} checks passed"
        if not self.ok:
            worst = self.failures[0]
            headline += f" — first failure: {worst.label}: {worst.detail[:160]}"
        if self.isolation != "bwrap":
            headline += f" (isolation: {self.isolation})"
        return headline

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "isolation": self.isolation,
            "total": self.total,
            "passed": self.passed,
            "failed": self.failed,
            "summary": self.summary(),
            "results": [item.as_dict() for item in self.results],
        }



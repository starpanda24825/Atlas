class SkillSandbox:
    """Runs untrusted skill code under time, memory and namespace limits.

    Cheap to construct — no subprocess is started until something runs, and the
    bubblewrap capability probe happens once per process.
    """

    def __init__(
        self,
        sandbox_dir: str | Path | None = None,
        *,
        timeout: float | None = None,
        memory_mb: int | None = None,
        isolation: str | None = None,
        network_whitelist: Sequence[str] | None = None,
        keep_artifacts: bool = True,
    ) -> None:
        self.sandbox_dir = Path(sandbox_dir or SKILL_SANDBOX_DIR)
        self.timeout = float(timeout if timeout is not None else SKILL_SANDBOX_TIMEOUT)
        self.memory_mb = int(memory_mb if memory_mb is not None else SKILL_SANDBOX_MEMORY_MB)
        self.keep_artifacts = keep_artifacts
        self.network_whitelist = tuple(
            SKILL_NETWORK_WHITELIST if network_whitelist is None else network_whitelist
        )

        requested = (isolation or SKILL_SANDBOX_ISOLATION or "auto").strip().lower()
        if requested in ("rlimits", "none", "off"):
            self.isolation = "rlimits"
        elif requested in ("bwrap", "bubblewrap", "strict"):
            if not _bwrap_available():
                raise SandboxUnavailable(
                    "SKILL_SANDBOX_ISOLATION asks for bubblewrap, but it is not usable "
                    "on this machine (missing, or unprivileged namespaces are denied). "
                    "Set ATLAS_SANDBOX_ISOLATION=rlimits to accept running skill code "
                    "with only a timeout and a memory cap."
                )
            self.isolation = "bwrap"
        else:
            self.isolation = "bwrap" if _bwrap_available() else "rlimits"

        # Scratch files the sandbox writes into every run directory. Kept so the
        # artifact listing can tell a skill's output from our own bookkeeping.
        self._internal_prefix = "_atlas_"

        if self.isolation != "bwrap":
            logger.warning(
                "skill sandbox is running at the %r level: the timeout and the %d MB "
                "memory cap apply, but skill code is NOT confined — it can reach the "
                "network and the whole filesystem",
                self.isolation,
                self.memory_mb,
            )

    # -- static analysis ------------------------------------------------

    def validate_skill(
        self, code_string: str, *, network_whitelist: Sequence[str] | None = None
    ) -> list[str]:
        """Warnings about ``code_string``, judged against this sandbox's rules.

        A thin wrapper around the module-level :func:`validate_skill`, so a
        caller holding a sandbox does not also have to import the function — and
        so the network whitelist used to judge the code is the same one this
        sandbox will enforce at run time. Passing a different whitelist here
        would describe a machine other than the one the skill runs on.
        """
        return validate_skill(
            code_string,
            network_whitelist=(
                self.network_whitelist if network_whitelist is None else network_whitelist
            ),
        )

    # -- description ----------------------------------------------------

    def describe(self) -> str:
        if self.isolation == "bwrap":
            return (
                f"bubblewrap (no network, read-only root, writes confined to "
                f"{GUEST_SANDBOX}), {self.timeout:.0f}s timeout, {self.memory_mb} MB cap"
            )
        return (
            f"rlimits only ({self.timeout:.0f}s timeout, {self.memory_mb} MB cap) — "
            "no network or filesystem confinement"
        )

    def __repr__(self) -> str:
        return f"SkillSandbox(isolation={self.isolation!r}, timeout={self.timeout:.0f})"

    # -- running --------------------------------------------------------

    def execute_in_sandbox(
        self,
        code_string: str,
        test_input: Any = None,
        *,
        function: str = "run",
        timeout: float | None = None,
        memory_mb: int | None = None,
        allow_network: bool = False,
        keep_artifacts: bool | None = None,
        files: Mapping[str, str | bytes] | None = None,
    ) -> SandboxResult:
        """Run one function of a skill against ``test_input``.

        ``test_input`` becomes the call's arguments: a mapping means keyword
        arguments, a list or tuple means positional ones, and anything else is
        passed as a single positional argument.

        ``files`` places input files in the run directory before the call, so a
        skill that reads a CSV can be tested at all. Keys are paths relative to
        the sandbox; a key given as the full guest path (``/tmp/atlas_sandbox/
        data.csv``) is accepted and means the same thing. Values are text or
        bytes. These files are inputs, so they are not listed as artifacts.

        ``allow_network`` drops the network namespace. It defaults to False and
        should only be set to True after the user has approved the skill's
        ``NETWORK:`` declaration — the static analysis reports what was asked
        for, it does not grant anything.
        """
        source = str(code_string or "")
        started = time.time()

        if not source.strip():
            return SandboxResult(
                success=False,
                output="",
                error="no code was supplied",
                execution_time=0.0,
                isolation=self.isolation,
            )

        limit = float(timeout if timeout is not None else self.timeout)
        memory = self._resolve_memory(memory_mb, source)
        keep = self.keep_artifacts if keep_artifacts is None else keep_artifacts

        try:
            run_dir = self._new_run_dir()
        except OSError as exc:
            return SandboxResult(
                success=False,
                output="",
                error=f"could not create a sandbox directory under {self.sandbox_dir}: {exc}",
                execution_time=time.time() - started,
                isolation=self.isolation,
            )

        paths = _RunPaths(run_dir)
        try:
            self._write_inputs(paths, source, test_input, function, memory, limit, files)
        except OSError as exc:
            if not keep:
                shutil.rmtree(run_dir, ignore_errors=True)
            return SandboxResult(
                success=False,
                output="",
                error=f"could not prepare the sandbox: {exc}",
                execution_time=time.time() - started,
                isolation=self.isolation,
            )

        argv, env, guest_skill_name = self._build_invocation(
            paths, allow_network=allow_network
        )

        timed_out = False
        exit_code: int | None = None
        try:
            with open(paths.stdout, "wb") as out, open(paths.stderr, "wb") as err:
                process = subprocess.Popen(
                    argv,
                    stdin=subprocess.DEVNULL,
                    stdout=out,
                    stderr=err,
                    cwd=str(run_dir),
                    env=env,
                    start_new_session=True,
                )
                try:
                    process.wait(timeout=limit)
                except subprocess.TimeoutExpired:
                    timed_out = True
                    _kill_group(process)
                exit_code = process.returncode
        except OSError as exc:
            if not keep:
                shutil.rmtree(run_dir, ignore_errors=True)
            return SandboxResult(
                success=False,
                output="",
                error=f"could not start the sandboxed process: {exc}",
                execution_time=time.time() - started,
                isolation=self.isolation,
            )

        # The skill has exited; read what it left behind.
        stdout, out_cut = _read_capped(paths.stdout, SKILL_SANDBOX_MAX_OUTPUT)
        stderr, err_cut = _read_capped(paths.stderr, SKILL_SANDBOX_MAX_OUTPUT)
        envelope = _read_envelope(paths.result)

        artifacts = self._collect_artifacts(run_dir, paths.inputs)

        if timed_out:
            error = (
                f"timed out after {limit:.1f}s and was killed. "
                f"Raise the limit only if the work is genuinely long; an infinite "
                f"loop in a skill is a bug.\n\n--- stderr ---\n{stderr}".rstrip()
            )
            result = SandboxResult(
                success=False,
                output=stdout,
                error=error,
                execution_time=time.time() - started,
                timed_out=True,
                isolation=self.isolation,
                exit_code=_TIMEOUT_EXIT,
                artifacts_dir=str(run_dir) if keep else None,
                artifacts=artifacts,
                output_truncated=out_cut or err_cut,
            )
        else:
            result = self._interpret(
                envelope=envelope,
                exit_code=exit_code,
                stdout=stdout,
                stderr=stderr,
                cut=out_cut or err_cut,
                memory_bytes=memory,
                elapsed=time.time() - started,
                run_dir=run_dir,
                keep=keep,
                artifacts=artifacts,
                function=function,
                guest_name=guest_skill_name,
                limit=limit,
            )

        if not keep:
            shutil.rmtree(run_dir, ignore_errors=True)

        logger.debug(
            "sandbox %s: %s (%.2fs, %s)",
            function,
            "ok" if result.success else "failed",
            result.execution_time,
            self.isolation,
        )
        return result

    def _interpret(
        self,
        *,
        envelope: dict[str, Any] | None,
        exit_code: int | None,
        stdout: str,
        stderr: str,
        cut: bool,
        memory_bytes: int,
        elapsed: float,
        run_dir: Path,
        keep: bool,
        artifacts: tuple[str, ...],
        function: str,
        guest_name: str,
        limit: float,
    ) -> SandboxResult:
        """Turn the child's exit state into a SandboxResult."""
        common = {
            "output": stdout,
            "execution_time": elapsed,
            "isolation": self.isolation,
            "exit_code": exit_code,
            "artifacts_dir": str(run_dir) if keep else None,
            "artifacts": artifacts,
            "output_truncated": cut,
        }

        if exit_code is not None and exit_code < 0:
            reason = _signal_reason(exit_code)
            hint = _blas_hint(stderr, memory_bytes)
            if reason == "SIGXFSZ":
                file_cap = max(memory_bytes, _MIN_FILE_BYTES)
                hint += (
                    f"\n\nIt wrote more than the {_mb(file_cap)} MB file-size cap. "
                    "Reduce what it writes, or raise ATLAS_SANDBOX_MEMORY_MB."
                )
            return SandboxResult(
                success=False,
                error=(
                    f"the sandboxed process was killed by {reason}. "
                    f"Nothing after that point ran.{hint}\n\n--- stderr ---\n{stderr}".rstrip()
                ),
                warnings=(hint.strip(),) if hint else (),
                **common,
            )

        if envelope is None:
            note = (
                f"the sandboxed process exited with code {exit_code} without reporting a "
                f"result — it most likely called os._exit(), or the interpreter died."
            )
            if stderr.strip():
                note += f"\n\n--- stderr ---\n{stderr.strip()}"
            return SandboxResult(success=False, error=note, **common)

        if envelope.get("ok"):
            return SandboxResult(
                success=True,
                return_value=envelope.get("return_value"),
                error=stderr.strip(),
                **common,
            )

        stage = envelope.get("stage") or "call"
        traceback_text = (envelope.get("traceback") or "").strip()
        lead = {
            "import": f"importing the skill failed — no top-level code in it ran to completion "
                      f"(module {guest_name})",
            "lookup": f"the skill does not define a usable {function}()",
            "call": f"{function}() raised",
        }.get(stage, f"{function}() failed")

        detail = f"{lead}:\n\n{traceback_text}"
        if stderr.strip():
            detail += f"\n\n--- stderr ---\n{stderr.strip()}"
        hint = _blas_hint(traceback_text + stderr, memory_bytes)
        if hint:
            detail += hint
        if "MemoryError" in traceback_text:
            detail += (
                f"\n\nThe {_mb(memory_bytes)} MB address-space cap was reached. If the "
                "skill needs more, declare it with a 'MEMORY: 1024' line in its docstring."
            )
        return SandboxResult(
            success=False,
            error=detail,
            warnings=(hint.strip(),) if hint else (),
            **common,
        )

    # -- test cycle -----------------------------------------------------

    def full_test_cycle(
        self,
        code_string: str,
        test_cases: Any = None,
        *,
        timeout: float | None = None,
        memory_mb: int | None = None,
        allow_network: bool = False,
        function: str = "run",
    ) -> TestReport:
        """Run the skill's ``test()``, then every supplied case.

        The first entry of the report is always ``test()`` — the skill's own
        ``test() -> bool`` self-check, which the skill schema requires. Each
        remaining entry is one element of ``test_cases``.

        A case is either a mapping of keyword arguments, or a mapping using the
        reserved keys:

        ``kwargs``
            passed to the function
        ``args``
            positional arguments
        ``files``
            mapping of input filename to contents, placed in the run directory
            before the call. A skill that reads a file cannot be tested without
            this, because each run starts with an empty directory.
        ``label``
            what to call this case in the report
        ``expect``
            a mapping of keys that must appear in the returned dict with those
            values. Without it, a case passes when the call returns at all.

        Returns a :class:`TestReport`; it never raises, because this runs
        immediately before the user is asked to approve a skill and a crash
        here would be indistinguishable from a crash in Atlas.
        """
        results: list[TestCaseResult] = []

        selfcheck = self.execute_in_sandbox(
            code_string,
            None,
            function="test",
            timeout=timeout,
            memory_mb=memory_mb,
            allow_network=allow_network,
        )
        if selfcheck.success:
            passed = selfcheck.return_value is True
            detail = (
                "test() returned True"
                if passed
                else _append_captured(
                    f"test() returned {selfcheck.return_value!r}, expected True", selfcheck
                )
            )
        else:
            passed = False
            detail = selfcheck.error.strip() or "test() could not be run"
        results.append(
            TestCaseResult(
                label="test()",
                passed=passed,
                detail=detail,
                execution_time=selfcheck.execution_time,
            )
        )

        for index, case in enumerate(_normalise_cases(test_cases)):
            args, kwargs, label, expect, files = case
            outcome = self.execute_in_sandbox(
                code_string,
                kwargs if kwargs else (args if args else None),
                function=function,
                timeout=timeout,
                memory_mb=memory_mb,
                allow_network=allow_network,
                files=files,
            )
            if not outcome.success:
                results.append(
                    TestCaseResult(
                        label=label,
                        passed=False,
                        detail=outcome.error.strip() or "the call failed",
                        execution_time=outcome.execution_time,
                    )
                )
                continue

            if expect is None:
                results.append(
                    TestCaseResult(
                        label=label,
                        passed=True,
                        detail=f"returned {_short(outcome.return_value)}",
                        execution_time=outcome.execution_time,
                    )
                )
                continue

            mismatch = _mismatched_expectations(outcome.return_value, expect)
            results.append(
                TestCaseResult(
                    label=label,
                    passed=not mismatch,
                    detail=(_append_captured(mismatch, outcome) if mismatch else
                            f"returned {_short(outcome.return_value)} as expected"),
                    execution_time=outcome.execution_time,
                )
            )

        report = TestReport(results=tuple(results), isolation=self.isolation)
        logger.info("skill test cycle: %s", report.summary())
        return report

    # -- maintenance ----------------------------------------------------

    def cleanup(self, keep_last: int = 0) -> int:
        """Delete run directories, keeping the ``keep_last`` newest.

        Run directories hold whatever the skill wrote, so they are not removed
        automatically — a caller that has finished with a result can ask for
        this, or set ``keep_artifacts=False``.
        """
        if not self.sandbox_dir.is_dir():
            return 0
        runs = sorted(
            (path for path in self.sandbox_dir.iterdir() if path.is_dir()),
            key=lambda path: path.stat().st_mtime,
            reverse=True,
        )
        removed = 0
        for path in runs[max(0, keep_last) :]:
            shutil.rmtree(path, ignore_errors=True)
            removed += 1
        return removed

    def stats(self) -> dict[str, Any]:
        """Small health summary, for a UI or a log line."""
        runs = 0
        if self.sandbox_dir.is_dir():
            runs = sum(1 for path in self.sandbox_dir.iterdir() if path.is_dir())
        return {
            "isolation": self.isolation,
            "sandbox_dir": str(self.sandbox_dir),
            "runs_kept": runs,
            "timeout": self.timeout,
            "memory_mb": self.memory_mb,
            "keep_artifacts": self.keep_artifacts,
            "network_whitelist": list(self.network_whitelist),
            "bwrap_available": _bwrap_available(),
        }

    # -- internals ------------------------------------------------------

    def _resolve_memory(self, override: int | None, source: str) -> int:
        """Memory cap for this call, honouring what the skill declared.

        A skill's ``MEMORY:`` request is clamped to
        ``SKILL_SANDBOX_MAX_MEMORY_MB``: the declaration comes from generated
        code, so it is a request, not a grant. An explicit ``memory_mb``
        argument from Atlas itself wins outright, since that is the operator
        speaking rather than the skill.
        """
        if override is not None:
            return max(1, int(override)) * 1024 * 1024
        if self.memory_mb != SKILL_SANDBOX_MEMORY_MB:
            # A sandbox constructed with an explicit cap is an operator choice.
            return max(1, self.memory_mb) * 1024 * 1024

        declared = declared_permissions(source).get("memory_mb")
        if not declared:
            return max(1, self.memory_mb) * 1024 * 1024
        if declared > SKILL_SANDBOX_MAX_MEMORY_MB:
            logger.warning(
                "skill asked for %d MB but the ceiling is %d MB — clamping",
                declared,
                SKILL_SANDBOX_MAX_MEMORY_MB,
            )
            declared = SKILL_SANDBOX_MAX_MEMORY_MB
        if declared > self.memory_mb:
            logger.info("skill declared MEMORY: %d MB — raising the cap for this run", declared)
        return max(1, declared) * 1024 * 1024

    def _new_run_dir(self) -> Path:
        self.sandbox_dir.mkdir(parents=True, exist_ok=True)
        name = f"{time.strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:8]}"
        run_dir = self.sandbox_dir / name
        run_dir.mkdir(mode=0o700)
        return run_dir

    def _write_inputs(
        self,
        paths: "_RunPaths",
        source: str,
        test_input: Any,
        function: str,
        memory_bytes: int,
        timeout: float,
        files: Mapping[str, str | bytes] | None = None,
    ) -> None:
        args, kwargs = _split_test_input(test_input)
        module_name = f"atlas_skill_{uuid.uuid4().hex[:8]}"
        for name, content in (files or {}).items():
            relative = _relative_input_path(name, paths.root)
            if relative is None:
                raise OSError(
                    f"cannot place {name!r} in the sandbox: it is not a path inside "
                    "the run directory"
                )
            destination = paths.root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, (bytes, bytearray)):
                destination.write_bytes(bytes(content))
            else:
                destination.write_text(str(content), encoding="utf-8")
            paths.inputs.add(relative.as_posix())
        paths.skill.write_text(source, encoding="utf-8")
        paths.harness.write_text(_HARNESS_SOURCE, encoding="utf-8")
        paths.job.write_text(
            json.dumps(
                {
                    "skill_path": paths.guest(paths.skill, self.isolation),
                    "function": function,
                    "args": [_jsonable(item) for item in args],
                    "kwargs": {key: _jsonable(item) for key, item in kwargs.items()},
                    "module_name": module_name,
                    "memory_bytes": memory_bytes,
                    "file_bytes": max(memory_bytes, _MIN_FILE_BYTES),
                    "timeout_seconds": timeout,
                }
            ),
            encoding="utf-8",
        )

    def _build_invocation(
        self, paths: "_RunPaths", *, allow_network: bool
    ) -> tuple[list[str], dict[str, str], str]:
        """The argv and environment for one sandboxed run."""
        guest_skill = paths.guest(paths.skill, self.isolation)
        guest_harness = paths.guest(paths.harness, self.isolation)
        guest_job = paths.guest(paths.job, self.isolation)
        guest_result = paths.guest(paths.result, self.isolation)

        if self.isolation == "bwrap":
            argv = self._bwrap_argv(paths, guest_harness, guest_job, guest_result, allow_network)
            env = {_SANDBOX_ENV_MARKER: "1", _SANDBOX_DIR_VAR: GUEST_SANDBOX}
            return argv, env, guest_skill

        # Degraded: the same harness, no namespaces. The environment is still
        # scrubbed, so a skill cannot read an API key out of os.environ even
        # though it can reach the network.
        argv = [
            sys.executable,
            str(paths.harness),
            str(paths.job),
            str(paths.result),
        ]
        env = {
            "PATH": "/usr/bin:/bin",
            "HOME": str(paths.root),
            "TMPDIR": str(paths.root),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
            "PYTHONHASHSEED": "0",
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONIOENCODING": "utf-8",
            _SANDBOX_ENV_MARKER: "1",
            _SANDBOX_DIR_VAR: str(paths.root),
        }
        return argv, env, str(paths.skill)

    def _bwrap_argv(
        self,
        paths: "_RunPaths",
        guest_harness: str,
        guest_job: str,
        guest_result: str,
        allow_network: bool,
    ) -> list[str]:
        argv = [shutil.which("bwrap") or "bwrap"]

        # Read-only pieces of the host a Python interpreter needs.
        for path in ("/usr", "/etc"):
            if Path(path).is_dir():
                argv += ["--ro-bind", path, path]
        for link in ("/bin", "/sbin", "/lib", "/lib64", "/usr/lib64"):
            target = Path(link)
            if target.is_symlink():
                # On merged-/usr systems /bin is a link to usr/bin. Recreate the
                # link rather than binding through it, so the guest sees one
                # consistent /usr instead of a duplicate tree.
                argv += ["--symlink", os.readlink(link), link]
            elif target.is_dir():
                argv += ["--ro-bind", link, link]

        guest_python = self._guest_python()
        if self._venv_root is not None:
            argv += ["--ro-bind", str(self._venv_root), GUEST_PYTHON_ROOT]

        # A fresh /tmp, with the run directory bound over the one path the
        # skill is allowed to write to.
        argv += [
            "--tmpfs", "/tmp",
            "--bind", str(paths.root), GUEST_SANDBOX,
            "--proc", "/proc",
            "--dev", "/dev",
            "--unshare-pid",
            "--unshare-uts",
            "--unshare-ipc",
            "--die-with-parent",
            "--new-session",
            "--clearenv",
            "--setenv", "PATH", f"{GUEST_PYTHON_ROOT}/bin:/usr/bin:/bin",
            "--setenv", "HOME", GUEST_SANDBOX,
            "--setenv", "TMPDIR", GUEST_SANDBOX,
            "--setenv", "LANG", "C.UTF-8",
            "--setenv", "PYTHONHASHSEED", "0",
            "--setenv", "PYTHONDONTWRITEBYTECODE", "1",
            "--setenv", "PYTHONIOENCODING", "utf-8",
            "--setenv", _SANDBOX_ENV_MARKER, "1",
            "--setenv", _SANDBOX_DIR_VAR, GUEST_SANDBOX,
        ]
        if not allow_network:
            argv += ["--unshare-net"]

        argv += [guest_python, guest_harness, guest_job, guest_result]
        return argv

    @property
    def _venv_root(self) -> Path | None:
        """The directory to bind as the guest's Python installation.

        None when Atlas is not running from a virtual environment, in which
        case the interpreter already lives under /usr, which is mounted
        read-only anyway.
        """
        prefix = Path(sys.prefix)
        if not (prefix / "pyvenv.cfg").is_file():
            return None
        return prefix

    def _guest_python(self) -> str:
        if self._venv_root is None:
            return sys.executable
        try:
            relative = Path(sys.executable).relative_to(self._venv_root)
        except ValueError:
            relative = Path("bin") / Path(sys.executable).name
        return f"{GUEST_PYTHON_ROOT}/{relative}"

    def _collect_artifacts(self, run_dir: Path, inputs: set[str]) -> tuple[str, ...]:
        """Files the skill left behind, as paths relative to the run directory.

        Inputs supplied by the caller are excluded: they were placed there by
        the sandbox, so reporting them as the skill's output would be wrong.
        """
        found: list[str] = []
        for path in sorted(run_dir.rglob("*")):
            if not path.is_file():
                continue
            if path.name in _INTERNAL_FILES:
                continue
            relative = path.relative_to(run_dir).as_posix()
            if relative in inputs:
                continue
            found.append(relative)
        return tuple(found)


@dataclass
class _RunPaths:
    """The files one run needs, and their names inside the sandbox."""

    root: Path
    #: Relative paths the caller supplied as inputs, so the artifact listing can
    #: leave them out.
    inputs: set[str] = field(default_factory=set)

    @property
    def skill(self) -> Path:
        return self.root / _SKILL_NAME

    @property
    def harness(self) -> Path:
        return self.root / _HARNESS_NAME

    @property
    def job(self) -> Path:
        return self.root / _JOB_NAME

    @property
    def result(self) -> Path:
        return self.root / _RESULT_NAME

    @property
    def stdout(self) -> Path:
        return self.root / _STDOUT_NAME

    @property
    def stderr(self) -> Path:
        return self.root / _STDERR_NAME

    def guest(self, path: Path, isolation: str) -> str:
        """Where ``path`` appears from inside the sandbox.

        Under bubblewrap the run directory is mounted at ``GUEST_SANDBOX``, so
        the guest path is fixed and the host path varies. At the rlimits level
        there is no mount, so both are the same.
        """
        if isolation != "bwrap":
            return str(path)
        return f"{GUEST_SANDBOX}/{path.name}"


def _relative_input_path(name: Any, run_dir: Path) -> Path | None:
    """Normalise a caller-supplied input name to a path inside the run directory.

    Both ``"data.csv"`` and the guest path a skill would actually open,
    ``"/tmp/atlas_sandbox/data.csv"``, are accepted, because a caller writing a
    test case naturally uses the same string in both places. Anything that
    would land outside the run directory is refused rather than quietly
    reinterpreted.
    """
    text = str(name).strip().replace("\\", "/")
    if not text:
        return None

    if text.startswith("/"):
        for prefix in (GUEST_SANDBOX, str(run_dir)):
            trimmed = prefix.rstrip("/")
            if text == trimmed:
                return None
            if text.startswith(trimmed + "/"):
                text = text[len(trimmed) + 1 :]
                break
        else:
            # Absolute, but not inside this run: refuse rather than silently
            # rewriting it into a relative path.
            return None

    if not text:
        return None
    candidate = Path(text)
    if candidate.is_absolute() or any(part == ".." for part in candidate.parts):
        return None
    return candidate


def _read_envelope(path: Path) -> dict[str, Any] | None:
    """Read the harness's result file, or None when it never got written."""
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return None
    if not raw.strip():
        return None
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        logger.warning("sandbox result file was not valid JSON: %r", raw[:200])
        return None
    return parsed if isinstance(parsed, dict) else None


def _short(value: Any, limit: int = 90) -> str:
    text = repr(value)
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _normalise_cases(
    test_cases: Any,
) -> list[tuple[list[Any], dict[str, Any], str, dict[str, Any] | None, dict[str, Any] | None]]:
    """Flatten ``test_cases`` into (args, kwargs, label, expect, files) tuples.

    A mapping is treated as reserved-key syntax only when it actually uses one
    of the reserved keys; otherwise it is the kwargs for a skill parameter
    genuinely called ``label`` or ``args``, which is unlikely but not
    impossible.
    """
    if test_cases is None:
        return []
    if isinstance(test_cases, Mapping):
        cases: list[Any] = [test_cases]
    elif isinstance(test_cases, (list, tuple)):
        cases = list(test_cases)
    else:
        cases = [test_cases]

    reserved = {"label", "args", "kwargs", "expect", "files"}
    normalised = []
    for index, case in enumerate(cases, start=1):
        if not isinstance(case, Mapping):
            normalised.append(([case], {}, f"case {index}", None, None))
            continue
        if not reserved.intersection(case):
            normalised.append(([], dict(case), f"case {index}", None, None))
            continue

        args: list[Any] = []
        raw_args = case.get("args")
        if isinstance(raw_args, (list, tuple)):
            args = list(raw_args)
        elif raw_args is not None:
            args = [raw_args]

        kwargs = case.get("kwargs")
        if not isinstance(kwargs, Mapping):
            # Anything not reserved is a skill parameter.
            kwargs = {key: value for key, value in case.items() if key not in reserved}

        expect = case.get("expect")
        if not isinstance(expect, Mapping):
            expect = None

        files = case.get("files")
        if not isinstance(files, Mapping):
            files = None

        label = str(case.get("label") or f"case {index}")
        normalised.append((args, dict(kwargs), label, expect, dict(files) if files else None))
    return normalised


def _mismatched_expectations(returned: Any, expect: Mapping[str, Any]) -> str:
    """Describe the first expected key that does not match, or "" when all do."""
    if not isinstance(returned, Mapping):
        return (
            f"the skill returned {_short(returned)}, not a dict, so the expected keys "
            f"{sorted(expect)} cannot be checked"
        )
    for key, wanted in expect.items():
        if key not in returned:
            return f"the returned dict has no {key!r} key (got {sorted(returned)})"
        actual = returned[key]
        if actual != wanted:
            return f"expected {key}={wanted!r}, got {actual!r}"
    return ""


